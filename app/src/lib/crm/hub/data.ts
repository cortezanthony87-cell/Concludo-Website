/**
 * Returns the count of met attention conditions.
 * Enforces Rule 5: "The attention figure is the count of met conditions, an integer from 0 to 11."
 */
export function getAttentionConditionsCount(conditions: CommAttentionCondition[] = HUB_ATTENTION_CONDITIONS): number {
  const met = conditions.filter((c) => c.status === 'met').length;
  return Math.min(Math.max(0, met), 11);
}

