/**
 * The synthetic workspace.
 *
 * Everything here is invented. No organisation, person, email address or phone
 * number below belongs to anybody. The addresses use `.example`, which is
 * reserved by RFC 2606 and can never be registered, so nothing can accidentally
 * be sent anywhere even if a future stage added sending.
 *
 * It is written by hand rather than generated, because each record is here to
 * demonstrate one behaviour the shell has to handle. Generated data produces a
 * hundred rows that all look the same and prove nothing. In particular:
 *
 * - An organisation with no recorded activity for nine weeks, to drive the
 *   quiet check without any alarming language.
 * - A record sitting well past its stage's typical duration with no next step,
 *   which is the single most useful thing a CRM can surface.
 * - A person with `do_not_contact`, so the interface has to respect a
 *   preference rather than merely store one.
 * - A value with `basis: 'inferred'` beside a value with `basis: 'stated'`, so
 *   the two are visibly different on the same screen.
 * - A proposal that would merge two records, so the destructive path is
 *   visible and is still only a proposal.
 * - A duplicate pair that the module recommends treating as separate, so the
 *   data quality view is not only a list of things to merge.
 * - An activity whose source needs review, so that phrase has something real
 *   to attach to.
 *
 * The workspace is a small Australian consulting practice with a real estate
 * agency among its clients, which is Concludo's stated go-to-market rather than
 * a generic software company.
 */
